function decision = nis_robust_range_policy(innovation_m, ...
        nonmeasurement_variance_m2, measurement_variance_m2, options)
%NIS_ROBUST_RANGE_POLICY Select normal, downweighted, or rejected range use.
%   The soft branch inflates only the independent range-noise variance until
%   the resulting scalar NIS equals the configured soft threshold. The hard
%   branch rejects the range row; callers may still retain other measurement
%   rows, such as depth.

if nargin < 4 || isempty(options)
    options = struct( ...
        'enabled', false, 'enable_rejection', false, ...
        'soft_threshold', 3.841, 'reject_threshold', 10.828, ...
        'minimum_weight', 0.10);
end
required_fields = {'enabled', 'enable_rejection', 'soft_threshold', ...
    'reject_threshold', 'minimum_weight'};
if ~isstruct(options) || ~all(isfield(options, required_fields))
    error('NIS robust options are incomplete.');
end
if ~isscalar(innovation_m) || ~isfinite(innovation_m) || ...
        ~isscalar(nonmeasurement_variance_m2) || ...
        ~isfinite(nonmeasurement_variance_m2) || ...
        nonmeasurement_variance_m2 < 0 || ...
        ~isscalar(measurement_variance_m2) || ...
        ~isfinite(measurement_variance_m2) || measurement_variance_m2 <= 0
    error('NIS robust policy inputs must be finite scalar variances.');
end
options.enabled = logical(options.enabled);
options.enable_rejection = logical(options.enable_rejection);

if ~isscalar(options.enabled) || ~isscalar(options.enable_rejection) || ...
        ~isscalar(options.soft_threshold) || ...
        ~isfinite(options.soft_threshold) || options.soft_threshold <= 0 || ...
        ~isscalar(options.reject_threshold) || ...
        ~isfinite(options.reject_threshold) || ...
        options.reject_threshold <= options.soft_threshold || ...
        ~isscalar(options.minimum_weight) || ...
        ~isfinite(options.minimum_weight) || options.minimum_weight <= 0 || ...
        options.minimum_weight > 1
    error('NIS reject threshold must exceed the soft threshold.');
end

base_s_m2 = nonmeasurement_variance_m2 + measurement_variance_m2;
raw_nis = innovation_m^2/base_s_m2;
effective_measurement_variance_m2 = measurement_variance_m2;
action_code = 0;

if options.enabled && options.enable_rejection && ...
        raw_nis > options.reject_threshold
    effective_measurement_variance_m2 = inf;
    action_code = 2;
elseif options.enabled && raw_nis > options.soft_threshold
    target_s_m2 = innovation_m^2/options.soft_threshold;
    effective_measurement_variance_m2 = max( ...
        measurement_variance_m2, target_s_m2-nonmeasurement_variance_m2);
    maximum_variance_m2 = measurement_variance_m2/options.minimum_weight;
    effective_measurement_variance_m2 = min( ...
        effective_measurement_variance_m2, maximum_variance_m2);
    action_code = 1;
end

if action_code == 2
    effective_s_m2 = inf;
    effective_nis = nan;
    information_weight = 0;
else
    effective_s_m2 = nonmeasurement_variance_m2 + ...
        effective_measurement_variance_m2;
    effective_nis = innovation_m^2/effective_s_m2;
    information_weight = measurement_variance_m2/ ...
        effective_measurement_variance_m2;
end

decision = struct( ...
    'action_code', action_code, ...
    'raw_nis', raw_nis, ...
    'base_innovation_variance_m2', base_s_m2, ...
    'effective_nis', effective_nis, ...
    'effective_innovation_variance_m2', effective_s_m2, ...
    'base_measurement_variance_m2', measurement_variance_m2, ...
    'effective_measurement_variance_m2', ...
        effective_measurement_variance_m2, ...
    'information_weight', information_weight);
end
