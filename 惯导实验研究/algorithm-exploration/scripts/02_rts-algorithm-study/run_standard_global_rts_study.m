function horizontal_error = calculate_horizontal_error_m(nav, truth)
    param = Param();
    truth_position = interp1(truth(:, 2), truth(:, 3:5), ...
        nav(:, 2), 'linear', nan);
    valid = all(isfinite(truth_position), 2);
    if ~all(valid)
        error('评价区间内存在无法插值真值的导航历元。');
    end
    latitude = truth_position(:, 1) * param.D2R;
    reference_latitude = mean(latitude);
    reference_height = mean(truth_position(:, 3));
    [rm, rn] = getRmRn(reference_latitude, param);
    north_error = (nav(:, 3) - truth_position(:, 1)) ...
        * param.D2R * (rm + reference_height);
    east_error = (nav(:, 4) - truth_position(:, 2)) ...
        * param.D2R * (rn + reference_height) * cos(reference_latitude);
    horizontal_error = hypot(north_error, east_error);
end

function [statistics, statistics_path, figure_path] = ...
        write_rts_horizontal_error_comparison( ...
        first_nav, first_name, first_mask, second_nav, second_name, ...
        second_mask, truth, result_dir, file_stem, figure_title)
%WRITE_RTS_HORIZONTAL_ERROR_COMPARISON 统一生成两种RTS的统计与曲线。
    if isempty(first_nav) || isempty(second_nav)
        error('%s或%s结果为空，无法绘制对比图。', first_name, second_name);
    end
    sample_count = size(second_nav, 1);
    if size(first_nav, 1) ~= sample_count || ...
            numel(first_mask) ~= sample_count || ...
            numel(second_mask) ~= sample_count
        error('%s、%s与平滑掩码的长度不一致。', first_name, second_name);
    end
    common_mask = first_mask(:) & second_mask(:);
    if ~any(common_mask)
        error('%s与%s没有共同的有效平滑区间。', first_name, second_name);
    end

    comparison_time = second_nav(common_mask, 2);
    first_error = calculate_horizontal_error_m( ...
        first_nav(common_mask, :), truth);
    second_error = calculate_horizontal_error_m( ...
        second_nav(common_mask, :), truth);
    statistics = table( ...
        [string(first_name); string(second_name)], ...
        [sqrt(mean(first_error .^ 2)); sqrt(mean(second_error .^ 2))], ...
        [mean(first_error); mean(second_error)], ...
        [prctile(first_error, 95); prctile(second_error, 95)], ...
        [max(first_error); max(second_error)], ...
        'VariableNames', {'method', 'horizontal_rmse_m', ...
        'horizontal_mean_m', 'horizontal_p95_m', 'horizontal_max_m'});
    statistics_path = fullfile(result_dir, [file_stem, '-statistics.csv']);
    writetable(statistics, statistics_path);

    comparison_figure = figure('Color', 'w', 'Visible', 'off', ...
        'Position', [100, 100, 1200, 680]);
    tiledlayout(comparison_figure, 2, 1, 'TileSpacing', 'compact', ...
        'Padding', 'compact');
    elapsed_hour = (comparison_time - comparison_time(1)) / 3600;
    nexttile;
    plot(elapsed_hour, first_error, 'Color', [0.85, 0.33, 0.10], ...
        'LineWidth', 1.0);
    hold on;
    plot(elapsed_hour, second_error, 'Color', [0, 0.45, 0.74], ...
        'LineWidth', 1.1);
    grid on;
    ylabel('水平误差 / m');
    title(figure_title, 'Interpreter', 'none');
    legend(first_name, second_name, 'Location', 'best');

    nexttile;
    plot(elapsed_hour, first_error - second_error, ...
        'Color', [0.47, 0.67, 0.19], 'LineWidth', 1.0);
    yline(0, '--k');
    grid on;
    xlabel('相对时间 / h');
    ylabel(sprintf('%s误差 - %s误差 / m', first_name, second_name));
    title(sprintf('正值表示%s的水平误差更小', second_name));

    figure_path = fullfile(result_dir, ...
        [file_stem, '-horizontal-error.png']);
    exportgraphics(comparison_figure, figure_path, 'Resolution', 200);
    close(comparison_figure);
end
