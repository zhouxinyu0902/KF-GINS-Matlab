%% 4. 与当前固定滞后算法统一比较
if compare_existing_fixed_lag
fixed_lag_dir = fullfile(cfg.outputfolder, ...
    sprintf('fixed-lag-rts-%s', position_error_unit));
method_names = {'前向EKF', 'lag1', 'lag2', 'lag3', 'lag4', ...
    '标准全局RTS'};
result_paths = { ...
    fullfile(fixed_lag_dir, sprintf( ...
    'simple-forward-ekf-%s.nav', position_error_unit)), ...
    fullfile(fixed_lag_dir, sprintf( ...
    'simple-rts-lag1-%s.nav', position_error_unit)), ...
    fullfile(fixed_lag_dir, sprintf( ...
    'simple-rts-lag2-%s.nav', position_error_unit)), ...
    fullfile(fixed_lag_dir, sprintf( ...
    'simple-rts-lag3-%s.nav', position_error_unit)), ...
