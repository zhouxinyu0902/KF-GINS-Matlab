        global_nav, "标准全局RTS", outputs.standard_global_rts_mask, ...
        truth, result_dir, 'standard-global-vs-double-rts', ...
        sprintf('%s / %s：2RTS 与标准全局 RTS', ...
        char(data_source), case_name));
    fprintf('2RTS与全局RTS对比统计：%s\n', double_statistics_path);
    fprintf('2RTS与全局RTS对比图：%s\n', double_figure_path);
