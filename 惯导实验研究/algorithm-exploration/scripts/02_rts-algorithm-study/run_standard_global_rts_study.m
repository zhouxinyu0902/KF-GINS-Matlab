    'simple-rts-lag4-%s.nav', position_error_unit)), ...
    outputs.standard_global_rts_path};
if any(~cellfun(@isfile, result_paths))
    missing_paths = result_paths(~cellfun(@isfile, result_paths));
    warning('缺少固定滞后对比文件，已跳过比较：%s', ...
        strjoin(missing_paths, ', '));
else
    truth = readmatrix(cfg.truthpath, 'FileType', 'text');
    nav_results = cellfun(@(path) readmatrix(path, 'FileType', 'text'), ...
        result_paths, 'UniformOutput', false);
    common_start_time = max(cellfun(@(nav) nav(1, 2), nav_results));
    common_end_time = min(cellfun(@(nav) nav(end, 2), nav_results));

    statistics = zeros(numel(nav_results), 5);
    for method_index = 1:numel(nav_results)
        nav = nav_results{method_index};
        mask = nav(:, 2) >= common_start_time ...
            & nav(:, 2) <= common_end_time;
        horizontal_error = calculate_horizontal_error_m( ...
            nav(mask, :), truth);
        statistics(method_index, :) = [ ...
            sum(mask), sqrt(mean(horizontal_error .^ 2)), ...
            mean(horizontal_error), ...
            prctile(horizontal_error, 95), max(horizontal_error)];
    end
    comparison = table(string(method_names(:)), ...
        repmat(common_start_time, numel(method_names), 1), ...
        repmat(common_end_time, numel(method_names), 1), ...
        statistics(:, 1), statistics(:, 2), statistics(:, 3), ...
        statistics(:, 4), statistics(:, 5), ...
        'VariableNames', {'method', 'start_time_s', 'end_time_s', ...
        'sample_count', 'horizontal_rmse_m', 'horizontal_mean_m', ...
        'horizontal_p95_m', 'horizontal_max_m'});
    comparison_path = fullfile(result_dir, ...
        'standard-global-rts-comparison.csv');
    writetable(comparison, comparison_path);
    fprintf('统一评价区间：%.2f s 至 %.2f s。\n', ...
        common_start_time, common_end_time);
    disp(comparison(:, {'method', 'horizontal_rmse_m', ...
        'horizontal_p95_m', 'horizontal_max_m'}));
    fprintf('对比统计：%s\n', comparison_path);
end
end

