%% 测距触发的标准全局 RTS：独立生成并与已有固定滞后结果评价
% 每次测距到来后，基于原始前向滤波记录重新平滑从起点到当前时刻的
% 全部历史。历史平滑结果不会反馈给前向 EKF，也不会作为下一次 RTS
% 的输入，从而避免重复使用量测。

