function range_ref=range_error_analysis(range,pva830,time_tol)
% 根据830位置计算水平距离
% 时间匹配
[index,valid]=findNearestTimeIndex(...
    range(:,1),...
    pva830(:,2),...
    time_tol);
range=range(valid,:);
index=index(valid);
% 参考位置
pos830=pva830(index,3:5);
% deg->rad
pos830(:,1:2)=deg2rad(pos830(:,1:2));
% 转局部坐标
glvs
% xyz830=pos2dxyz(pos830, pos830(1,:)');
% 信标位置
beacon=range(:,4:6);
% xyzBeacon=pos2dxyz(beacon,pos830(1,:)');
% 水平距离
% range_ref=sqrt((xyzBeacon(:,1)-xyz830(:,1)).^2 + (xyzBeacon(:,2)-xyz830(:,2)).^2);
range_ref=RCompu(beacon,pos830);

range_meas=range(:,3);
% 残差
error=range_meas-range_ref;
fprintf("Range数量:%d\n",length(error));
fprintf("Mean = %.3f m\n",mean(error));
fprintf("RMSE = %.3f m\n",...
    sqrt(mean(error.^2)));
fprintf("MAX = %.3f m\n",...
    max(abs(error)));
%% 绘图
figure;
plot(error,...
    'LineWidth',1.2);
grid on;
xlabel("测距序号");
ylabel("Range error / m");
title("声学测距水平距离误差");
end
