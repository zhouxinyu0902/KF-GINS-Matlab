%% 时间最近邻匹配
function [index, valid] = findNearestTimeIndex(...
    targetTime,...
    sourceTime,...
    time_tol)
n = length(targetTime);
index = nan(n,1);
valid = false(n,1);
for i = 1:n
    % 找最近时间点
    [dt_min, idx] = min(...
        abs(sourceTime-targetTime(i)));
    % 判断是否满足容差
    if dt_min <= time_tol
        index(i)=idx;
        valid(i)=true;

    else

        warning(...
            ['第 %d 个Range时间 %.6f ',...
            '没有匹配点，最小时间差 %.6f s'],...
            i,...
            targetTime(i),...
            dt_min);
    end
end
end
%%
function writeMatrixSafe( ...
    data, ...
    output_file, ...
    dataName)
try
    writematrix( ...
        data, ...
        output_file, ...
        'Delimiter',' ');
    fprintf( ...
        '%s已写入：%s\n', ...
        dataName, ...
        output_file);
catch ME
    error( ...
        '%s写入失败：%s', ...
        dataName, ...
        ME.message);
end
end
%%
function checkdata11(a)
d = diff(a);
tol = 1e-10;
step = 0.01;
missing_indices = find( ...
    d > (step + tol));
if isempty(missing_indices)
    disp('该向量是完整的0.01 s等差时间序列，无缺失数据。');
else
    disp('发现缺失数据：');
    for i = 1:length(missing_indices)
        idx = missing_indices(i);
        num_missing = ...
            round(d(idx)/step)-1;
        start_val = a(idx);
        end_val   = a(idx+1);
        fprintf( ...
            ['在 a(%d)=%.6f 和 ', ...
            'a(%d)=%.6f 之间，', ...
            '缺失 %d 个数据。\n'], ...
            idx, ...
            start_val, ...
            idx+1, ...
            end_val, ...
            num_missing);
    end
end
