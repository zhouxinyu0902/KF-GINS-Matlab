function adap_factor_visualize(z,z_back)
disp('------------------------------前向滤波---------------------------')
disp('| 新息残差 |量测更新后的残差|   α  |    d²   |   χ²阈值    | 异常 |')
disp('---------------------------------------------------------------------')
for i=1:length(z)
    % 使用固定的宽度，例如 10 个字符，来对齐数字和表头
    % %.3f: 浮点数，3位小数
    % %10.3f: 宽度为10，3位小数
    % %6d: 宽度为6，整数
    fprintf('|%10.3f|%18.3f|%8.3f|%8.3f|%8.3f|%6d|\n', z(i,1:6));
end
disp('---------------------------------------------------------------------')

disp('------------------------------后向滤波--------------     -------------')
disp('| 新息残差 |量测更新后的残差|   α  |    d²   |   χ²阈值    | 异常 |')
disp('---------------------------------------------------------------------')
for i=1:length(z)
    % 使用固定的宽度，例如 10 个字符，来对齐数字和表头
    % %.3f: 浮点数，3位小数
    % %10.3f: 宽度为10，3位小数
    % %6d: 宽度为6，整数
    fprintf('|%10.3f|%18.3f|%8.3f|%8.3f|%8.3f|%6d|\n', z_back(i,1:6));
end
disp('---------------------------------------------------------------------')

zz=zeros(length(z)+1,6);
zz_back=zz;
zz(2:end,:)=z;
zz_back(1:end-1,:)=z_back;
disp('------------------------------前向，后向滤波--------------     -------------')
disp('| 新息残差 |量测更新后的残差|新息残差 |量测更新后的残差|')
disp('---------------------------------------------------------------------')
for i=1:length(zz)
    fprintf('|%10.3f|%10.3f|%10.3f|%10.3f|\n',zz(i,1:2), zz_back(i,1:2));
end
disp('---------------------------------------------------------------------')
end